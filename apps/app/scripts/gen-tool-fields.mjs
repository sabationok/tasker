#!/usr/bin/env node
/**
 * Regenerates src/features/drafts/tool-fields.gen.ts from the running server's MCP `tools/list`: per write tool, each
 * input field's Ukrainian `title`, kind and options — what the draft card and the edit form label and render.
 * Run: node scripts/gen-tool-fields.mjs   (reads TASKER_API_KEY / TASKER_API_URL from .env.local)
 */
import { readFileSync, writeFileSync } from 'node:fs';

const env = Object.fromEntries(
  readFileSync(new URL('../.env.local', import.meta.url), 'utf8')
    .split('\n')
    .filter((l) => l.includes('='))
    .map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1).trim()]),
);
const base = env.TASKER_API_URL ?? 'http://127.0.0.1:3109';
const headers = { Authorization: `Bearer ${env.TASKER_API_KEY}`, 'Content-Type': 'application/json', Accept: 'application/json, text/event-stream' };
const rpc = async (body, sid) => {
  const res = await fetch(`${base}/mcp`, { method: 'POST', headers: { ...headers, ...(sid ? { 'Mcp-Session-Id': sid } : {}) }, body: JSON.stringify(body) });
  const text = await res.text();
  const data = text.split('\n').find((l) => l.startsWith('data: '));
  return { sid: res.headers.get('mcp-session-id'), json: data ? JSON.parse(data.slice(6)) : text ? JSON.parse(text) : null };
};

const { sid } = await rpc({ jsonrpc: '2.0', id: 0, method: 'initialize', params: { protocolVersion: '2025-06-18', capabilities: {}, clientInfo: { name: 'gen-tool-fields', version: '0' } } });
await rpc({ jsonrpc: '2.0', method: 'notifications/initialized' }, sid);
const { json } = await rpc({ jsonrpc: '2.0', id: 1, method: 'tools/list' }, sid);

/** Collapse anyOf/nullable into one kind. */
function kindOf(p) {
  const variants = p.anyOf ?? p.oneOf ?? [p];
  const nonNull = variants.filter((v) => v.type !== 'null');
  const v = nonNull[0] ?? p;
  const nullable = variants.length > nonNull.length;
  if (nonNull.every((x) => 'const' in x)) return { kind: 'enum', options: nonNull.map((x) => x.const), nullable };
  if (v.enum) return { kind: 'enum', options: v.enum, nullable };
  if (v.type === 'string' && v.format === 'date-time') return { kind: 'datetime', nullable };
  if (v.type === 'string' && (v.format === 'date' || /\\d\{4\}-\\d\{2\}-\\d\{2\}\$/.test(v.pattern ?? ''))) return { kind: 'date', nullable };
  if (v.type === 'string' && v.format === 'uuid') return { kind: 'ref', nullable };
  if (v.type === 'string') return { kind: v.maxLength && v.maxLength > 500 ? 'text' : 'string', nullable };
  if (v.type === 'integer' || v.type === 'number') return { kind: 'number', nullable };
  if (v.type === 'boolean') return { kind: 'boolean', nullable };
  if (v.type === 'array') return { kind: 'array', nullable };
  return { kind: 'object', nullable };
}

const out = {};
for (const t of json.result.tools) {
  if (t.annotations?.readOnlyHint) continue;
  out[t.name] = { title: t.title ?? t.annotations?.title ?? null, fields: {} };
  for (const [k, p] of Object.entries(t.inputSchema?.properties ?? {})) out[t.name].fields[k] = { title: p.title ?? k, ...kindOf(p) };
}
const file = new URL('../src/features/drafts/tool-fields.gen.ts', import.meta.url);
writeFileSync(
  file,
  `/* Generated by scripts/gen-tool-fields.mjs from the server's MCP tools/list — do not edit by hand. */\n` +
    `import type { ToolFields } from './tool-fields';\n\nexport const TOOL_FIELDS: Record<string, ToolFields> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`tools: ${Object.keys(out).length} → ${file.pathname}`);
